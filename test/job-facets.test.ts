test("role, seniority and Indian places read correctly on the labelled fixtures", () => {
  const roleMisses = TITLES.filter(([title, role]) => roleFamily(title) !== role);
  const levelMisses = TITLES.filter(([title, , level]) => (seniority(title) ?? "") !== level);
  const placeMisses = PLACES.filter(([location, cities, states]) => {
    const got = indiaPlaces(location);
    return JSON.stringify(got.cities) !== JSON.stringify(cities) || JSON.stringify([...got.states].sort()) !== JSON.stringify([...states].sort());
  });
  const pct = (misses: number, total: number) => `${(100 * (total - misses) / total).toFixed(1)}% (${total - misses}/${total})`;
  console.log(`job facets on fixtures: role ${pct(roleMisses.length, TITLES.length)}, seniority ${pct(levelMisses.length, TITLES.length)}, places ${pct(placeMisses.length, PLACES.length)}`);
  for (const [title, role] of roleMisses) console.log(`  role   ${title}: got ${roleFamily(title)}, want ${role}`);
  for (const [title, , level] of levelMisses) console.log(`  level  ${title}: got ${seniority(title) ?? "-"}, want ${level || "-"}`);
  for (const [location] of placeMisses) console.log(`  place  ${location}: got ${JSON.stringify(indiaPlaces(location))}`);
  // Floors, so a rule change that breaks more than a handful of these fails the suite.
  expect(TITLES.length).toBeGreaterThanOrEqual(150);
  expect(roleMisses.length / TITLES.length).toBeLessThanOrEqual(0.05);
  expect(levelMisses.length / TITLES.length).toBeLessThanOrEqual(0.05);
  expect(placeMisses.length).toBe(0);
});

test("seniority falls back to the stated experience only when the title says nothing", () => {
  expect(seniority("Java Developer", { min: 0, max: 1 })).toBe("entry");
  expect(seniority("Java Developer", { min: 3, max: 5 })).toBe("mid");
  expect(seniority("Java Developer", { min: 6 })).toBe("senior");
  expect(seniority("Java Developer", { min: 12 })).toBe("lead");
  expect(seniority("Junior Java Developer", { min: 6 })).toBe("entry");
  expect(seniority("Java Developer", null)).toBeUndefined();
});

test("Indian places are read only for roles open in India", () => {
  expect(jobFacets({ title: "Engineer", location: "Kochi, Japan", eligibleCountries: ["JP"] }).cities).toBeUndefined();
  expect(jobFacets({ title: "Engineer", location: "Salem, OR", eligibleCountries: ["US"] }).cities).toBeUndefined();
  expect(jobFacets({ title: "Senior Data Engineer", location: "Bangalore, India", eligibleCountries: ["IN"] }))
    .toEqual({ role: "data-engineering", seniority: "senior", cities: ["Bengaluru"], states: ["Karnataka"] });
});
